create table if not exists public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null default '',
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.customers (
  id bigint generated by default as identity primary key,
  full_name text not null check (char_length(full_name) between 2 and 120),
  phone text not null check (char_length(phone) between 7 and 24),
  email text,
  status text not null default 'potential' check (status in ('potential', 'active', 'inactive', 'vip')),
  notes text not null default '',
  last_contacted_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index if not exists customers_phone_unique on public.customers (phone);
create index if not exists customers_status_idx on public.customers (status);
create index if not exists customers_created_at_idx on public.customers (created_at desc);

create table if not exists public.contact_requests (
  id bigint generated by default as identity primary key,
  full_name text not null check (char_length(full_name) between 2 and 120),
  phone text,
  email text,
  subject text not null default '',
  message text not null check (char_length(message) between 2 and 5000),
  status text not null default 'new' check (status in ('new', 'contacted', 'resolved', 'spam')),
  source text not null default 'website',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (coalesce(nullif(phone, ''), nullif(email, '')) is not null)
);

create index if not exists contact_requests_status_idx on public.contact_requests (status);
create index if not exists contact_requests_created_at_idx on public.contact_requests (created_at desc);

